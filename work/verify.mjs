import { chromium } from '/Users/rupertgermann/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';

const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1500, height: 1000 }, deviceScaleFactor: 1 });
const errors = [], network = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
page.on('request', r => { if (/^https?:/.test(r.url())) network.push(r.url()); });
await page.goto(pathToFileURL(process.cwd() + '/outputs/castle-at-dawn.html').href);
await page.waitForFunction(() => window.__sceneReady === true, { timeout: 60000 });
await page.waitForTimeout(1800);
const before = await page.evaluate(() => window.__castle.stats());
await page.screenshot({ path: 'work/initial.png' });
assert.equal(await page.locator('body').innerText(), '', 'The visible scene has no words');
assert.equal(network.length, 0, 'The HTML is independent of network resources');
await page.mouse.move(750, 500); await page.mouse.down(); await page.mouse.move(1050, 570, { steps: 25 }); await page.mouse.up();
await page.waitForTimeout(800);
const rotated = await page.evaluate(() => window.__castle.stats());
assert.ok(Math.abs(rotated.camera[0] - before.camera[0]) > 5, 'Dragging rotates the actual camera');
await page.mouse.wheel(0, -650); await page.waitForTimeout(800);
const zoomed = await page.evaluate(() => window.__castle.stats());
assert.ok(zoomed.distance < rotated.distance * .9, 'Wheel zoom moves closer');
await page.screenshot({ path: 'work/rotated-detail.png' });
await page.mouse.dblclick(750, 500); await page.waitForTimeout(800);
assert.ok(Math.abs((await page.evaluate(() => window.__castle.stats())).distance - before.distance) < 1, 'Double click restores composition');
await page.setViewportSize({ width: 390, height: 844 }); await page.waitForTimeout(1000);
await page.screenshot({ path: 'work/mobile.png' });
assert.equal(await page.locator('canvas').count(), 1);
assert.deepEqual(errors, [], 'No browser or shader errors');
const report = { before, rotated, zoomed, externalRequests: network.length, errors, verifiedAt: new Date().toISOString() };
await writeFile('work/verification.json', JSON.stringify(report, null, 2));
console.log(JSON.stringify(report, null, 2));
await browser.close();
